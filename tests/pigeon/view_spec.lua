---@module 'luassert'
describe("pigeon native floating views", function()
  it("preserves tools, layout and independent view ownership through native lifecycle events", function()
    local result = vim.system({ "python3", "tests/pigeon/view.py", vim.v.progpath }, { text = true }):wait(35000)
    assert.are.equal(0, result.code, result.stderr)
    local report = vim.json.decode(result.stdout)
    assert.are.equal(5, report.cycles)
    assert.is_true(report.draft_preserved)
    assert.is_true(report.receiver_pid_preserved)
    assert.is_true(report.layout_and_zoom_preserved)
    assert.is_true(report.independent_views)
    assert.is_true(report.creator_and_origin_exit_preserved)
    assert.is_true(report.extended_keys_preserved)
    assert.is_true(report.rollback_and_conflicts)
  end)
end)
